<?php

namespace ASENHA\Classes;

/**
 * Class for Show Custom Taxonomy Filters module
 *
 * @since 6.9.5
 */
class Show_Custom_Taxonomy_Filters {
    // Excluded taxonomies
    private $inapplicable_taxonomies = array(
        'category',
        // Post Categories
        'product_cat',
        // WooCommerce Product Categories
        'asenha_code_snippet_category',
        // ASE Code Snippets Categories
        'asenha-media-category',
    );

    /**
     * Built-in taxonomies that stay eligible alongside custom taxonomies.
     *
     * @var string[]
     */
    private $included_builtin_taxonomies = array('post_tag', 'post_format');

    /**
     * Enabled taxonomy slugs for the current request, keyed by hierarchy.
     *
     * @var array<string, string[]>
     */
    private $cached_enabled_taxonomy_slugs = array();

    /**
     * Show custom (hierarchical) taxonomy filter(s) for all post types.
     *
     * @since 1.0.0
     */
    public function show_custom_taxonomy_filters( $post_type ) {
        $object_taxonomies = get_object_taxonomies( $post_type, 'objects' );
        array_walk( $object_taxonomies, [$this, 'output_taxonomy_filter'] );
    }

    /**
     * Output filter on the post type's list table for a taxonomy
     *
     * @since 1.0.0
     */
    public function output_taxonomy_filter( $taxonomy ) {
        // Show filter if taxonomy is hierarchical.
        // Free shows every taxonomy that passes this check. Pro limits it to the saved allowlist.
        if ( true === $taxonomy->hierarchical && !in_array( $taxonomy->name, $this->inapplicable_taxonomies, true ) ) {
            $show_hierarchical_filter = true;
            if ( $show_hierarchical_filter ) {
                $this->render_additional_filter( $taxonomy );
            }
        }
    }

    /**
     * Render additional filter
     * 
     * @since 6.9.7
     */
    public function render_additional_filter( $taxonomy ) {
        $show_option_all_label = sprintf( 'All %s', ucwords( $taxonomy->label ) );
        if ( property_exists( $taxonomy, 'labels' ) ) {
            $taxonomy_labels = $taxonomy->labels;
            if ( property_exists( $taxonomy_labels, 'all_items' ) && !empty( $taxonomy_labels->all_items ) ) {
                $show_option_all_label = $taxonomy->labels->all_items;
            }
        }
        $request_key = $this->get_filter_request_key( $taxonomy );
        $selected = '';
        if ( isset( $_GET[$request_key] ) ) {
            // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- List-table filter form, same as core.
            $selected = sanitize_title( wp_unslash( $_GET[$request_key] ) );
        }
        $dropdown = wp_dropdown_categories( array(
            'show_option_all' => $show_option_all_label,
            'orderby'         => 'name',
            'order'           => 'ASC',
            'hide_empty'      => false,
            'hide_if_empty'   => true,
            'selected'        => $selected,
            'hierarchical'    => true,
            'name'            => $request_key,
            'taxonomy'        => $taxonomy->name,
            'value_field'     => 'slug',
            'echo'            => false,
        ) );
        if ( !is_string( $dropdown ) || '' === $dropdown ) {
            return;
        }
        // Core hardcodes the "All" option as value 0. A slug query for 0 matches nothing.
        $dropdown = preg_replace(
            "/value='0'/",
            "value=''",
            $dropdown,
            1
        );
        echo $dropdown;
        // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- HTML is generated by wp_dropdown_categories().
    }

    /**
     * Query-string key for a taxonomy filter dropdown.
     *
     * A taxonomy with a public query var keeps that key so WordPress can filter it.
     * A taxonomy with query_var turned off uses its slug. Those are applied in the admin list query.
     *
     * @since 9.2.0
     *
     * @param WP_Taxonomy $taxonomy Taxonomy object.
     * @return string
     */
    private function get_filter_request_key( $taxonomy ) {
        if ( is_string( $taxonomy->query_var ) && '' !== $taxonomy->query_var ) {
            return $taxonomy->query_var;
        }
        return $taxonomy->name;
    }

    /**
     * Limit the admin list query for taxonomies that have no query var.
     *
     * WordPress only maps a taxonomy argument into tax_query when query_var is registered.
     * Registering one here would make the taxonomy publicly queryable.
     *
     * @since 9.2.0
     *
     * @param WP_Query $query Main admin query.
     * @return void
     */
    public function filter_admin_list_by_taxonomy( $query ) {
        if ( !is_admin() || !$query->is_main_query() ) {
            return;
        }
        global $pagenow;
        if ( 'edit.php' !== $pagenow ) {
            return;
        }
        $post_type = $query->get( 'post_type' );
        if ( !is_string( $post_type ) || '' === $post_type ) {
            $post_type = 'post';
        }
        $taxonomies = get_object_taxonomies( $post_type, 'objects' );
        if ( empty( $taxonomies ) || !is_array( $taxonomies ) ) {
            return;
        }
        $tax_query = array();
        foreach ( $taxonomies as $taxonomy ) {
            if ( is_string( $taxonomy->query_var ) && '' !== $taxonomy->query_var ) {
                continue;
            }
            if ( !isset( $_GET[$taxonomy->name] ) ) {
                // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- List-table filter form, same as core.
                continue;
            }
            $slug = sanitize_title( wp_unslash( $_GET[$taxonomy->name] ) );
            if ( '' === $slug || '0' === $slug ) {
                continue;
            }
            $tax_query[] = array(
                'taxonomy' => $taxonomy->name,
                'field'    => 'slug',
                'terms'    => $slug,
            );
        }
        if ( empty( $tax_query ) ) {
            return;
        }
        $existing_tax_query = $query->get( 'tax_query' );
        if ( is_array( $existing_tax_query ) && !empty( $existing_tax_query ) ) {
            $tax_query = array_merge( $existing_tax_query, $tax_query );
        }
        $query->set( 'tax_query', $tax_query );
    }

}
